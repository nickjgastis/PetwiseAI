// Compiles src/content/blog/*.md into src/content/blog/posts.generated.js so the
// browser bundle and the Node prerenderer share the same post data.

const fs = require('fs');
const path = require('path');
const { marked } = require('marked');

const DIR = path.join(__dirname, '../src/content/blog');
const OUT = path.join(DIR, 'posts.generated.js');

const parseFrontMatter = (raw, file) => {
    const match = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
    if (!match) throw new Error(`${file}: missing front matter`);
    const data = {};
    for (const line of match[1].split('\n')) {
        const i = line.indexOf(':');
        if (i === -1) continue;
        const key = line.slice(0, i).trim();
        const value = line.slice(i + 1).trim();
        try {
            data[key] = JSON.parse(value);
        } catch {
            data[key] = value;
        }
    }
    return { data, body: match[2].trim() };
};

const youtubeId = (url) => {
    const m = url.match(/(?:youtu\.be\/|youtube\.com\/(?:watch\?v=|embed\/))([\w-]{11})/);
    return m ? m[1] : null;
};

const renderer = new marked.Renderer();
renderer.paragraph = (text) => {
    const plain = text.replace(/<[^>]+>/g, '').trim();
    const id = /^https?:\/\/\S+$/.test(plain) ? youtubeId(plain) : null;
    if (id) {
        return `<div class="post-embed"><iframe src="https://www.youtube-nocookie.com/embed/${id}" title="PetWise video" loading="lazy" allow="accelerometer; encrypted-media; gyroscope; picture-in-picture" allowfullscreen></iframe></div>\n`;
    }
    return `<p>${text}</p>\n`;
};
renderer.image = (href, title, alt) =>
    `<figure><img src="${href}" alt="${alt || ''}" loading="lazy" />${title ? `<figcaption>${title}</figcaption>` : ''}</figure>`;
renderer.link = (href, title, text) => {
    const external = /^https?:\/\//.test(href);
    return `<a href="${href}"${external ? ' target="_blank" rel="noopener noreferrer"' : ''}>${text}</a>`;
};

marked.setOptions({ renderer, gfm: true, breaks: false, headerIds: true, mangle: false });

const build = () => {
    const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.md'));
    const posts = files.map((file) => {
        const { data, body } = parseFrontMatter(fs.readFileSync(path.join(DIR, file), 'utf8'), file);
        const words = body.split(/\s+/).length;
        return {
            slug: data.slug || file.replace(/\.md$/, ''),
            title: data.title,
            date: data.date,
            updated: data.updated || data.date,
            author: data.author || 'PetWise Team',
            description: data.description || '',
            cover: data.cover || '',
            tags: data.tags || [],
            readingMinutes: Math.max(1, Math.round(words / 220)),
            html: marked.parse(body)
        };
    });
    posts.sort((a, b) => (a.date < b.date ? 1 : -1));

    const redirectsFile = path.join(DIR, '_redirects.json');
    const redirects = fs.existsSync(redirectsFile) ? JSON.parse(fs.readFileSync(redirectsFile, 'utf8')) : {};

    const out = `// Generated by scripts/build-blog.js. Do not edit.\n\nexport const POSTS = ${JSON.stringify(posts, null, 2)};\n\nexport const POST_REDIRECTS = ${JSON.stringify(redirects, null, 2)};\n`;
    fs.writeFileSync(OUT, out);
    console.log(`[blog] ${posts.length} posts compiled`);
};

build();

if (process.argv.includes('--watch')) {
    let timer;
    fs.watch(DIR, (_, file) => {
        if (!file || !file.endsWith('.md')) return;
        clearTimeout(timer);
        timer = setTimeout(build, 150);
    });
}
